const {chromium} = require('/opt/homebrew/lib/node_modules/@playwright/cli/node_modules/playwright');
const path = require('node:path');
const assert = require('node:assert/strict');
(async () => {
  const browser = await chromium.launch({headless:true, executablePath:"/Users/afr/Library/Caches/ms-playwright/chromium_headless_shell-1187/chrome-mac/headless_shell"});
  const page = await browser.newPage({viewport:{width:1440,height:900},colorScheme:'light'});
  const errors=[];
  page.on('pageerror', error=>errors.push(error.message));
  const url = 'file://' + path.join(__dirname, 'index.html');
  await page.goto('file://' + path.join(__dirname, 'demo.webp'));
  await page.waitForTimeout(2400);
  await page.locator('img').screenshot({path:path.join(__dirname,'demo-still.png')});
  await page.goto(url);
  await page.screenshot({path:path.join(__dirname,'shot-desktop.png')});
  console.log('desktop loaded');
  await page.locator('#replay').click();
  await page.waitForTimeout(3650);
  assert.equal(await page.locator('#pasted').inputValue(), 'i was going to type all of this. then i remembered i could just say it.');
  assert.equal(await page.locator('#blob-label').textContent(), 'pasted');
  await page.locator('#pasted').fill('my own words');
  await page.locator('#replay').click();
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('#pasted').inputValue(), 'my own words');
  console.log('replay and cancellation passed');
  await page.locator('#hold').focus();
  await page.keyboard.down('Space');
  await page.waitForTimeout(750);
  await page.keyboard.up('Space');
  assert.equal(await page.locator('#pasted').inputValue(), 'i was going to type');
  assert.equal(await page.locator('#hold').getAttribute('aria-pressed'), 'false');
  console.log('keyboard hold/release passed');
  await page.locator('#next').click();
  await page.waitForTimeout(500);
  assert.ok(await page.locator('#tape').evaluate(el=>el.scrollLeft)>300);
  await page.locator('header a[href="#install"]').click();
  await page.waitForFunction(()=>document.querySelector('#install').getBoundingClientRect().right<=1441);
  await page.locator('#copy').click();
  await page.waitForFunction(()=>/copied|selected/.test(document.querySelector('#copy-status').textContent));
  console.log('navigation and copy passed');
  await page.locator('a[href="#actual"]').first().click();
  await page.waitForTimeout(500);
  await page.locator('#recording-toggle').click();
  assert.equal(await page.locator('#recording-toggle').getAttribute('aria-pressed'),'true');
  await page.locator('#recording-toggle').click();
  assert.match(await page.locator('#recording-slot img').getAttribute('src'),/demo-still/);
  console.log('recording toggle passed');
  await page.emulateMedia({reducedMotion:'reduce'});
  await page.goto(url);
  await page.locator('#replay').click();
  assert.equal(await page.locator('#transcript').textContent(),'i was going to type all of this. then i remembered i could just say it.');
  await page.locator('#replay').click();
  assert.equal(await page.locator('#blob-label').textContent(),'pasted');
  console.log('reduced motion passed');
  for(const width of [390,768,1440]) {
    await page.setViewportSize({width,height:900});
    await page.goto(url);
    assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth), `outer overflow at ${width}`);
    const missing = await page.locator('img').evaluateAll(imgs=>imgs.filter(img=>img.complete&&!img.naturalWidth).map(img=>img.src));
    assert.deepEqual(missing,[]);
    const overflowing = await page.locator('.column').evaluateAll(nodes=>nodes.filter(n=>n.scrollHeight>n.clientHeight+1).map(n=>n.id));
    assert.deepEqual(overflowing,[],`column overflow at ${width}`);
    await page.screenshot({path:path.join(__dirname,width===390?'shot-mobile.png':width===768?'shot-tablet.png':'shot-desktop.png'),fullPage:width===390});
    console.log(`${width}px layout passed`);
  }
  await page.locator('header a[href="#numbers"]').click();
  await page.screenshot({path:path.join(__dirname,'shot-numbers.png')});
  await page.goto(url);
  await page.emulateMedia({colorScheme:'dark'});
  await page.screenshot({path:path.join(__dirname,'shot-dark.png')});
  assert.deepEqual(errors,[]);
  console.log('no browser errors');
  await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
